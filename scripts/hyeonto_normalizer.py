def _normalize_old_hangul(text: str) -> str:
    """옛한글 자모를 현대 한글 호환 자모로 변환"""
    result = []
    for ch in text:
        if ch in OLD_HANGUL_JAMO_MAP:
            result.append(OLD_HANGUL_JAMO_MAP[ch])
        else:
            result.append(ch)
    return ''.join(result)


def normalize_marker_list(markers: List[str]) -> List[str]:
    """마커 리스트 일괄 정규화"""
    return [normalize_hyeonto_marker(m) for m in markers]


def get_normalization_mapping(marker: str) -> Optional[str]:
    """
    마커의 정규화 매핑 정보 반환
    
    Returns:
        정규화 대표형 (매핑이 없으면 None)
    """
    return NORMALIZATION_TABLE.get(marker)


def get_normalization_stats(markers: List[str]) -> Dict:
    """
    마커 리스트에 대한 정규화 통계
    
    Returns:
        {
            'total': 전체 마커 수,
            'normalized': 정규화된 마커 수,
            'unchanged': 변경 없는 마커 수,
            'normalization_pairs': [(원본, 정규화)...],
            'before_unique': 정규화 전 고유 마커 수,
            'after_unique': 정규화 후 고유 마커 수,
            'reduction_rate': 고유값 감소율 (%)
        }
    """
    normalized = [normalize_hyeonto_marker(m) for m in markers]
    
    pairs = [(orig, norm) for orig, norm in zip(markers, normalized) if orig != norm]
    
    before_unique = len(set(markers))
    after_unique = len(set(normalized))
    
    return {
        'total': len(markers),
        'normalized': len(pairs),
        'unchanged': len(markers) - len(pairs),
        'normalization_pairs': Counter(pairs).most_common(50),
        'before_unique': before_unique,
        'after_unique': after_unique,
        'reduction_rate': (1 - after_unique / before_unique) * 100 if before_unique > 0 else 0
    }


# ============================================================================
# 6. 역정규화 테이블 (대표형 → 변이형 목록)
# ============================================================================
def get_variant_forms(representative: str) -> List[str]:
    """
    대표형에 해당하는 모든 변이형 반환
    
    Args:
        representative: 대표형 마커 (예: "를")
    
    Returns:
        변이형 목록 (예: ["을", "를"])
    """
    variants = [representative]
    for pattern, rep in NORMALIZATION_TABLE.items():
        if rep == representative and pattern != representative:
            variants.append(pattern)
    return list(set(variants))


