def normalize_hyeonto_marker(marker: str, 
                             use_josa: bool = True,
                             use_eomi: bool = True,
                             use_complex: bool = True) -> str:
    """
    현토 마커를 정규화된 대표형으로 변환
    
    Args:
        marker: 원본 현토 마커 (예: "을", "인댄")
        use_josa: 조사 변이형 정규화 적용
        use_eomi: 어미 변이형 정규화 적용
        use_complex: 복합형 정규화 적용
    
    Returns:
        정규화된 마커 (예: "를", "ㄴ댄")
    
    Examples:
        >>> normalize_hyeonto_marker("을")
        '를'
        >>> normalize_hyeonto_marker("인댄")
        'ㄴ댄'
        >>> normalize_hyeonto_marker("하야")
        '하여'
    """
    if not marker:
        return marker
    
    # 공백 제거
    marker = marker.strip()
    
    # 옛한글 자모 → 현대 한글 호환 자모 변환
    marker = _normalize_old_hangul(marker)
    
    # 정규화 테이블에서 직접 매칭 (가장 빠름)
    if marker in NORMALIZATION_TABLE:
        return NORMALIZATION_TABLE[marker]
    
    # 부분 매칭: 마커 내에 정규화 대상 패턴이 포함된 경우
    # (긴 패턴부터 치환하여 중복 치환 방지)
    result = marker
    for pattern, replacement in NORMALIZATION_TABLE.items():
        if pattern in result:
            result = result.replace(pattern, replacement)
    
    return result


