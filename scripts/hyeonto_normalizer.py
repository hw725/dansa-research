def _build_normalization_table() -> Dict[str, str]:
    """모든 정규화 규칙을 하나의 테이블로 병합 (긴 패턴 우선)"""
    merged = {}
    merged.update(COMPLEX_NORMALIZATION)
    merged.update(EOMI_NORMALIZATION)
    merged.update(JOSA_NORMALIZATION)
    
    # 길이순 정렬 (긴 것 먼저 매칭)
    return dict(sorted(merged.items(), key=lambda x: -len(x[0])))

NORMALIZATION_TABLE = _build_normalization_table()


